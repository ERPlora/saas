# --- Hub ------------------------------------------------------------------------------------------


class TestHub:
    def test_its_id_is_a_uuid7_the_hub_service_shares(self, hub):
        """``Hub.id`` is generated by the SaaS and names the hub's database (PLAN-SAAS §2)."""
        assert isinstance(hub.id, uuid.UUID) and hub.id.version == 7

    def test_a_new_hub_is_preparing_and_has_never_been_ready(self, hub):
        assert (hub.status, hub.ready_at, hub.deletion_requested_at) == (
            Hub.Status.PREPARING,
            None,
            None,
        )

    def test_it_starts_at_state_version_one_never_pushed(self, hub):
        assert (hub.state_version, hub.pushed_state_version, hub.pending_hub_call) == (
            1,
            0,
            "",
        )

    def test_its_defaults_are_the_spanish_market(self, hub):
        assert (hub.timezone, hub.language) == ("Europe/Madrid", "en")

    def test_it_reads_as_its_name_and_slug(self, hub):
        assert str(hub) == "Bar Manolo (bar-manolo)"

    def test_the_slug_is_unique_across_the_platform(self, hub):
        with pytest.raises(IntegrityError), transaction.atomic():
            Hub.objects.create(
                slug="bar-manolo", name="Another Bar Manolo", country="ES"
            )

    @pytest.mark.parametrize(
        "slug", ["hub", "hubs", "www", "Bar", "-bar", "bar_manolo", "a" * 64]
    )
    def test_a_slug_outside_the_shared_rule_is_refused(self, slug):
        """``live.slugs``: one DNS label, never a reserved name (shared with hub-next)."""
        with pytest.raises(ValidationError) as refused:
            Hub(slug=slug, name="Bar", country="ES").full_clean()
        assert "slug" in refused.value.message_dict

    @pytest.mark.parametrize("slug", ["bar_manolo", "Bar", "hubs", "-bar"])
    def test_an_invalid_slug_is_never_saved(self, slug):
        """Review of L1-A, finding 1: whatever path writes a business, its address is a valid DNS label."""
        with pytest.raises(ValidationError):
            Hub.objects.create(slug=slug, name="Bar", country="ES")

        assert not Hub.objects.exists()

    def test_the_status_choices_are_the_account_planes(self):
        assert list(Hub.Status.values) == [
            "preparing",
            "active",
            "past_due",
            "suspended",
            "deleting",
            "deleted",
        ]

    def test_a_deleted_business_can_be_recovered_for_ninety_days(self, hub):
        requested = timezone.now()
        hub.deletion_requested_at = requested

        assert hub.purge_after == requested + timedelta(days=90)
        assert Hub(slug="x-bar", name="X").purge_after is None

    def test_the_business_type_is_optional_and_survives_its_retirement(self, hub):
        from hubs.models import BusinessType

        bar = BusinessType.objects.create(code="bar", name_en="Bar")
        hub.business_type = bar
        hub.save()
        bar.delete()
        hub.refresh_from_db()

        assert hub.business_type is None

    def test_the_pushed_version_never_runs_ahead_of_the_state(self, hub):
        with pytest.raises(IntegrityError), transaction.atomic():
            Hub.objects.filter(pk=hub.pk).update(pushed_state_version=2)


