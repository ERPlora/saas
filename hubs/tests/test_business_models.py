class TestHubOwnershipTransfer:
    def _offer(self, hub, owner, other_user, **extra):
        return HubOwnershipTransfer.objects.create(
            hub=hub,
            from_user=owner,
            to_user=other_user,
            from_email=owner.email,
            to_email=other_user.email,
            expires_at=timezone.now() + HubOwnershipTransfer.WINDOW,
            **extra,
        )

    def test_an_offer_is_pending_for_seven_days(self, hub, owner, other_user):
        offer = self._offer(hub, owner, other_user)

        assert (offer.status, HubOwnershipTransfer.WINDOW) == (
            "pending",
            timedelta(days=7),
        )
        assert not offer.is_expired

    def test_one_pending_offer_at_a_time_per_hub(self, hub, owner, other_user):
        self._offer(hub, owner, other_user)

        with pytest.raises(IntegrityError), transaction.atomic():
            self._offer(hub, owner, other_user)

    def test_a_resolved_offer_does_not_block_the_next(self, hub, owner, other_user):
        self._offer(hub, owner, other_user, status=HubOwnershipTransfer.Status.DECLINED)

        assert self._offer(hub, owner, other_user).status == "pending"

    def test_the_trail_survives_the_accounts_it_names(self, hub, owner, other_user):
        offer = self._offer(hub, owner, other_user)
        owner.delete()
        other_user.delete()
        offer.refresh_from_db()

        assert (offer.from_user, offer.to_user) == (None, None)
        assert (offer.from_email, offer.to_email) == (
            "owner@example.com",
            "other@example.com",
        )

    def test_past_its_window_it_is_expired(self, hub, owner, other_user):
        offer = self._offer(hub, owner, other_user)
        offer.expires_at = timezone.now() - timedelta(seconds=1)

        assert offer.is_expired


