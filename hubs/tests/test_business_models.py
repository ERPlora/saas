class TestHubMember:
    def test_a_member_is_attached_to_one_hub(self, hub, owner):
        member = HubMember.objects.create(
            hub=hub, user=owner, role=HubMember.Role.OWNER
        )

        assert member.hub == hub and member.id.version == 7
        assert list(owner.hub_members.all()) == [member]

    def test_the_same_person_can_belong_to_several_hubs(self, hub, other_hub, owner):
        HubMember.objects.create(hub=hub, user=owner, role=HubMember.Role.OWNER)
        HubMember.objects.create(
            hub=other_hub, user=owner, role=HubMember.Role.EMPLOYEE
        )

        assert owner.hub_members.count() == 2

    def test_a_person_cannot_be_added_twice_to_the_same_hub(self, hub, owner):
        HubMember.objects.create(hub=hub, user=owner, role=HubMember.Role.OWNER)

        with pytest.raises(IntegrityError), transaction.atomic():
            HubMember.objects.create(hub=hub, user=owner, role=HubMember.Role.ADMIN)

    def test_it_defaults_to_the_least_privilege(self, hub, other_user):
        assert (
            HubMember.objects.create(hub=hub, user=other_user).role
            == HubMember.Role.EMPLOYEE
        )

    def test_the_four_roles_carry_the_hub_prefix(self):
        """Round 11: the customer's roles travel to the hub as they are; ``hub_`` keeps them apart
        from the platform's (``platform_*``)."""
        assert list(HubMember.Role.values) == [
            "hub_owner",
            "hub_admin",
            "hub_manager",
            "hub_employee",
        ]

    def test_the_hierarchy_puts_the_owner_first(self):
        rank = HubMember.RANK

        assert (
            rank["hub_owner"]
            < rank["hub_admin"]
            < rank["hub_manager"]
            < rank["hub_employee"]
        )

    def test_a_hub_has_at_most_one_owner(self, hub, owner, other_user):
        HubMember.objects.create(hub=hub, user=owner, role=HubMember.Role.OWNER)

        with pytest.raises(IntegrityError), transaction.atomic():
            HubMember.objects.create(
                hub=hub, user=other_user, role=HubMember.Role.OWNER
            )

    @pytest.mark.parametrize("role", ["member", "owner", "admin", "", "superuser"])
    def test_a_role_outside_the_four_is_never_stored(self, hub, other_user, role):
        """Fail closed (old ``test_hub_member``: an unknown role grants nothing; ``test_members_role_escalation``:
        no seeded role, no write). The old ``Role`` table could be emptied from the admin; these four live
        in code, and a key outside them, a retired one included, never reaches a membership, whatever
        writes it (the admin, a data migration, an ``update()``): the access checks rank it nowhere."""
        with pytest.raises(IntegrityError), transaction.atomic():
            HubMember.objects.create(hub=hub, user=other_user, role=role)

    def test_an_unanswered_invitation_is_pending_and_expires_after_its_window(
        self, hub, other_user
    ):
        invited = timezone.now()
        member = HubMember.objects.create(
            hub=hub,
            user=other_user,
            role=HubMember.Role.EMPLOYEE,
            invited_at=invited,
            invitation_expires_at=invited + HubMember.INVITATION_WINDOW,
        )

        assert HubMember.INVITATION_WINDOW == timedelta(days=7)
        assert member.is_pending
        assert not member.is_expired(invited + timedelta(days=6))
        assert member.is_expired(invited + timedelta(days=7))

    def test_an_answered_membership_never_expires(self, hub, owner):
        member = HubMember.objects.create(
            hub=hub, user=owner, role=HubMember.Role.OWNER, accepted_at=timezone.now()
        )

        assert not member.is_pending
        assert not member.is_expired(timezone.now() + timedelta(days=365))

    def test_deleting_the_hub_removes_its_memberships(self, hub, owner):
        HubMember.objects.create(hub=hub, user=owner, role=HubMember.Role.OWNER)
        hub.delete()

        assert HubMember.objects.count() == 0

    def test_a_role_has_a_translated_label(self, hub, owner):
        from django.utils import translation

        member = HubMember(hub=hub, user=owner, role=HubMember.Role.MANAGER)
        with translation.override("es"):
            assert member.get_role_display() == "Encargado"


