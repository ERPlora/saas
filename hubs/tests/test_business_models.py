class TestSubscription:
    def test_a_hub_has_one_subscription_on_a_plan(self, hub, free_plan):
        subscription = Subscription.objects.create(hub=hub, plan=free_plan)

        assert hub.subscription == subscription
        assert (subscription.status, subscription.billing_interval) == (
            "active",
            "month",
        )
        assert subscription.id.version == 7

    def test_a_plan_in_use_cannot_be_deleted(self, hub, free_plan):
        Subscription.objects.create(hub=hub, plan=free_plan)

        with pytest.raises(ProtectedError):
            free_plan.delete()

    def test_a_trial_lends_another_plan_until_it_ends(self, hub, free_plan):
        starter = Plan.objects.create(
            slug="starter", name_en="Starter", price_monthly=Decimal("29")
        )
        now = timezone.now()
        subscription = Subscription.objects.create(
            hub=hub,
            plan=free_plan,
            trial_plan=starter,
            trial_start=now,
            trial_end=now + timedelta(days=15),
        )

        assert subscription.effective_plan(now) == starter
        assert subscription.effective_plan(now + timedelta(days=15)) == free_plan

    def test_without_a_trial_the_plan_is_its_own(self, hub, free_plan):
        assert (
            Subscription(hub=hub, plan=free_plan).effective_plan(timezone.now())
            == free_plan
        )

    def test_an_item_is_a_module_from_the_plan_or_bought(self, hub, free_plan):
        subscription = Subscription.objects.create(hub=hub, plan=free_plan)
        item = SubscriptionItem.objects.create(
            subscription=subscription, module_slug="inventory"
        )

        assert (item.source, item.valid_until, item.stripe_item_id) == (
            "purchase",
            None,
            "",
        )
        assert list(SubscriptionItem.Source.values) == ["plan", "purchase"]

    def test_a_module_appears_once_per_subscription(self, hub, free_plan):
        subscription = Subscription.objects.create(hub=hub, plan=free_plan)
        SubscriptionItem.objects.create(
            subscription=subscription, module_slug="inventory"
        )

        with pytest.raises(IntegrityError), transaction.atomic():
            SubscriptionItem.objects.create(
                subscription=subscription, module_slug="inventory", source="plan"
            )

    def test_the_module_slug_is_the_label_of_an_app(self, hub, free_plan):
        subscription = Subscription.objects.create(hub=hub, plan=free_plan)
        with pytest.raises(ValidationError) as refused:
            SubscriptionItem(
                subscription=subscription, module_slug="Inventory-App"
            ).full_clean()
        assert "module_slug" in refused.value.message_dict

    def test_an_item_is_live_until_its_date(self, hub, free_plan):
        now = timezone.now()
        subscription = Subscription.objects.create(hub=hub, plan=free_plan)
        open_ended = SubscriptionItem(
            subscription=subscription, module_slug="a", valid_until=None
        )
        ending = SubscriptionItem(
            subscription=subscription,
            module_slug="b",
            valid_until=now + timedelta(days=1),
        )

        assert open_ended.is_live(now) and ending.is_live(now)
        assert not ending.is_live(now + timedelta(days=1))
