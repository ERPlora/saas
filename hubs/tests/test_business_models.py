class TestBillingProfile:
    def test_it_holds_the_identity_erplora_invoices(self, owner):
        profile = BillingProfile.objects.create(
            owner=owner,
            billing_name="Manolo SL",
            tax_id="B12345678",
            billing_address="Calle Mayor 1",
            billing_city="Madrid",
            billing_postal_code="28001",
            billing_country="ES",
            billing_email="facturas@example.com",
        )

        assert profile.id.version == 7
        assert str(profile) == "Manolo SL"
        assert profile.same_as_business is False

    def test_every_field_but_the_owner_may_wait_for_the_checkout(self, owner):
        profile = BillingProfile.objects.create(owner=owner)

        profile.full_clean()
        assert str(profile) == str(profile.id)

    def test_it_reads_as_its_tax_id_without_a_name(self, owner):
        assert str(BillingProfile(owner=owner, tax_id="B12345678")) == "B12345678"

    def test_the_stripe_customer_is_indexed_for_the_webhook(self):
        assert BillingProfile._meta.get_field("stripe_customer_id").db_index

    def test_one_profile_pays_for_several_hubs(self, owner, hub, other_hub):
        profile = BillingProfile.objects.create(owner=owner)
        Hub.objects.filter(pk__in=[hub.pk, other_hub.pk]).update(
            billing_profile=profile
        )

        assert profile.hubs.count() == 2

    def test_a_profile_with_hubs_cannot_be_deleted(self, owner, hub):
        profile = BillingProfile.objects.create(owner=owner)
        hub.billing_profile = profile
        hub.save()

        with pytest.raises(ProtectedError):
            profile.delete()

    def test_deleting_the_owner_keeps_the_profile(self, owner):
        """ERPlora's invoices must stay resolvable after the account is gone."""
        profile = BillingProfile.objects.create(owner=owner, billing_name="Manolo SL")
        owner.delete()
        profile.refresh_from_db()

        assert profile.owner is None


